export function getLangMeta(lang?: string | null): LangMeta {
  return LANGUAGES.find((l) => l.code === lang) || LANGUAGES[0];
}

export function t(lang: LangCode, key: string): string {
  return DICT[lang]?.[key] ?? DICT.en[key] ?? key;
}

export function formatLocalizedHijriMonth(lang: LangCode, monthIndex1Based: number, fallback: string): string {
  const arr = HIJRI_MONTHS_I18N[lang];
  if (!arr) return fallback;
  return arr[(monthIndex1Based - 1 + 12) % 12] || fallback;
}
