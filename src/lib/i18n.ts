export function getLangMeta(lang?: string | null): LangMeta {
  return LANGUAGES.find((l) => l.code === lang) || LANGUAGES[0];
}

export function t(lang: LangCode, key: string): string {
  return DICT[lang]?.[key] ?? DICT.en[key] ?? key;
}

export function tp(lang: LangCode, phrase: string): string {
  return translatePhrase(lang, phrase);
}

export function getModuleSubtitle(lang: LangCode, moduleId: string, fallback = ""): string {
  const key = MODULE_SUBTITLE_KEYS[moduleId];
  if (key) return t(lang, key);
  return tp(lang, fallback);
}

export function localizePrayerName(lang: LangCode, raw: string): string {
  if (!raw) return raw;
  const base = raw.split(" (")[0].trim().toLowerCase();
  if (base === "fajr") return t(lang, "prayerFajr");
  if (base === "sunrise") return t(lang, "prayerSunrise");
  if (base === "dhuhr" || base === "zuhr") return t(lang, "prayerDhuhr");
  if (base === "asr") return t(lang, "prayerAsr");
  if (base === "maghrib") return t(lang, "prayerMaghrib");
  if (base === "isha") return t(lang, "prayerIsha");
  if (base.includes("jumu")) return t(lang, "prayerJumuah");
  if (base === "witr") return t(lang, "prayerWitr");
  return tp(lang, raw);
}

export function formatLocalizedWeekday(lang: LangCode, weekday: string): string {
  if (!weekday || lang === "en") return weekday;
  const firstWord = weekday.split(/[\s,(]/)[0].trim().toLowerCase();
  return WEEKDAYS_MAP[firstWord]?.[lang] || weekday;
}

export function formatLocalizedHijriMonth(lang: LangCode, monthIndex1Based: number, fallback: string): string {
  const arr = HIJRI_MONTHS_I18N[lang];
  if (!arr) return fallback;
  return arr[(monthIndex1Based - 1 + 12) % 12] || fallback;
}
